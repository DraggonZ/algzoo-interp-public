"""Frozen mechanism scorer (2026-10-21, from round 3): does a candidate do ARC's 12 jobs by ARC's mechanism?

Usage:  python -u score_mechanism.py <weights.npz | module.py | ARC>
Candidates as in score_twin.py (weights in ARC's neuron order). Added after round 2 (decision of 2026-10-21):
the jobs tests of score_twin.py could be passed by a change of basis that leaves the network's function unchanged
(round 2: rotating memory and neuron 3). Here each job's test is one that a change of basis, or a different reference,
does not pass. Jobs 1, 2, 3, 5, 6, 8 and 12 keep score_twin.py's tests (they test single named neurons' on/off
behaviour or ratios that a mixing of neurons would break). Jobs 4, 7, 9, 10 and 11 get new tests:

 4  keep gate cuts against the second-largest: constructed lists (largest at step 0, second at step 1, test number at
    step 4); the smallest test number that turns neuron 5 on, fitted as a x largest + b x second over a grid.
    Pass: b >= 0.5 and |a| <= 0.2 (ARC: b 0.74, a 0.02).
 7  hiding references are ARC's mixes: constructed lists (previous largest P at step 1, record M at step 2, test number
    1 or 2 steps later); each hiding neuron's switch-off point fitted as p x P + m x M. Pass: score_twin.py's job 7,
    and every neuron's p within 0.35 of ARC's at both delays (ARC: one step after, 6 and 8 follow P, 7 follows M,
    1 mostly M; two steps after, 1 and 8 follow P).
 9  memory turns votes by rotation, basis-free: eigenvalues of the full recurrent matrix in the commonest on/off
    pattern (steps 4-8); a mode's memory participation is sum over memory neurons of l_i r_i / (l . r) (left and right
    eigenvectors; unchanged by relabelling, rescaling or mixing neurons inside the memory, and near 0 for a mode that
    only drives the memory or that another path cancels). Pass: at least 2 turning pairs (3-177 degrees) of modulus
    >= 0.7 with memory participation >= 0.5 (ARC: 83, 125 and 43 degrees).
10  switch-off ages on a rotating code: score_twin.py's job 10 and job 9 above.
11  neuron 3 reads the gap from the hiding neurons and the network uses it (neuron3/README.md S1, G2): neuron 3's input
    from the hiding neurons is replaced at every step by (a) a per-(step, age) fit g (largest - second) + c on the
    list's own numbers (an analysis fit on the candidate's own run), (b) the same with another list's gap from the
    same cell. Pass: score_twin.py's job 11, (a) within 5 points of the intact accuracy, (b) at least 10 points
    below (a) (ARC in the notes: 2.8 and 25 points).

Last line: MECH jobs=<n>/12 (and the list of passes). Ranking from round 3 (decision of 2026-10-21):
mechanism count first, transplant mean (score_twin.py) second; the frozen score_twin.py count is reported
alongside. Do not edit this file (its hash is in LEDGER.md)."""
import sys
from collections import Counter
import numpy as np, torch, scipy.linalg as sl

sys.path.insert(0, "/data/output/research/algzoo/20261017_handbuilt/faithful_twin")
from score_twin import load, lists, run, so_far, jobs, T, N, example, HID, MEM, DEV, DT  # noqa: E402

XS = torch.linspace(-1.0, 4.0, 5001, device=DEV, dtype=DT)


def first_x(W, X, cond):
    """X: [n, 10] constructed lists differing only at one step (values XS); cond(H) -> bool [n]; smallest XS meeting it."""
    H, _ = run(T(W), X); ok = cond(H); i = torch.nonzero(ok).flatten()
    return XS[i[0]].item() if len(i) else np.nan


def keep_cut(W):
    rows = []
    for M in (1.5, 2.0, 2.5):
        for S in (0.3, 0.6, 0.9, 1.2):
            X = torch.full((len(XS), 10), -1.0, device=DEV, dtype=DT); X[:, 0] = M; X[:, 1] = S; X[:, 4] = XS
            rows.append((M, S, first_x(W, X, lambda H: H[:, 5, 5] > 0)))
    A = np.array([[M, S, 1] for M, S, _ in rows]); y = np.array([c for *_, c in rows]); ok = ~np.isnan(y)
    if ok.sum() < 4: return np.nan, np.nan
    co, *_ = np.linalg.lstsq(A[ok], y[ok], rcond=None); return co[0], co[1]


def hiding_refs(W):
    """{k: [p for each hiding neuron]}: weight of the previous largest in each switch-off point, k steps after a record."""
    out = {}
    for k in (1, 2):
        rows = []
        for P in (0.5, 0.9, 1.3):
            for M in (1.6, 2.0, 2.4):
                X = torch.full((len(XS), 10), -1.0, device=DEV, dtype=DT); X[:, 1] = P; X[:, 2] = M; X[:, 2 + k] = XS
                rows.append((P, M, [first_x(W, X, lambda H, j=j: H[:, 2 + k, j] <= 0) for j in HID]))
        A = np.array([[P, M, 1] for P, M, _ in rows]); Y = np.array([o for *_, o in rows]); ps = []
        for i in range(4):
            ok = ~np.isnan(Y[:, i]); ps.append(np.linalg.lstsq(A[ok], Y[ok, i], rcond=None)[0][0] if ok.sum() >= 4 else np.nan)
        out[k] = ps
    return out


def memory_modes(W, X):
    H, _ = run(T(W), X); on = H > 0
    pats = Counter(map(lambda q: q.tobytes(), on[:, 4:9].reshape(-1, 16).cpu().numpy()))
    top = np.frombuffer(pats.most_common(1)[0][0], dtype=bool)
    ev, L, R = sl.eig(np.diag(top.astype(float)) @ W[1], left=True, right=True); modes = []
    for k in range(len(ev)):
        l = ev[k]
        if np.imag(l) <= 0: continue
        lr = np.conj(L[:, k]) * R[:, k]; pm = float(np.real(lr[MEM].sum() / lr.sum()))
        modes.append((abs(l), np.degrees(abs(np.angle(l))), pm))
    return [m for m in modes if 3 < m[1] < 177 and m[0] >= 0.7 and m[2] >= 0.5], modes


def gap_use(W, n=400_000, seed=21):
    """neuron3/README.md S1 and G2: neuron 3's input from the hiding neurons, D_t = W[3, hiding] h_hiding(t-1), replaced
    at every step t >= 1 by (a) a per-(step, age of the largest) fit g (m1 - m2) + c on the list's own two largest so
    far (through step t-1), (b) the same with the gap of another list in the same cell. Returns accuracies."""
    Wt = T(W); X = lists(n, seed); H, _ = run(Wt, X); Xc = X.cpu().numpy()
    D = (H[:, :, HID] @ Wt[1][3, HID]).cpu().numpy()                 # D[:, t] enters neuron 3 at step t + 1
    _, _, _, age = so_far(X); agn = age.cpu().numpy(); rng = np.random.default_rng(5)
    rep_a = np.zeros((n, 10)); rep_b = np.zeros((n, 10))
    for t in range(1, 10):
        v = -np.sort(-Xc[:, :t], 1); gap = v[:, 0] - (v[:, 1] if t >= 2 else 0.0); y = D[:, t - 1]; ag = agn[:, t - 1]
        for a in range(t):
            m = np.flatnonzero(ag == a)
            if len(m) < 50: rep_a[m, t] = rep_b[m, t] = y[m]; continue
            A = np.c_[gap[m], np.ones(len(m))]; c, *_ = np.linalg.lstsq(A, y[m], rcond=None)
            rep_a[m, t] = A @ c; rep_b[m, t] = np.c_[gap[rng.permutation(m)], np.ones(len(m))] @ c
    def acc(rep):
        R_ = None if rep is None else torch.tensor(rep, device=DEV, dtype=DT); h = torch.zeros(n, 16, device=DEV, dtype=DT)
        for t in range(10):
            p = h @ Wt[1].T + X[:, t:t + 1] * Wt[0]
            if rep is not None and t >= 1: p = p.clone(); p[:, 3] = p[:, 3] - h[:, HID] @ Wt[1][3, HID] + R_[:, t]
            h = torch.relu(p)
        return ((h @ Wt[2].T).argmax(1) == X.argsort(1, descending=True)[:, 1]).double().mean().item()
    return acc(None), acc(rep_a), acc(rep_b)


def mechanism(W, seed=7):
    J = jobs(W, seed); passed = {i + 1: p for i, (_, _, p) in enumerate(J)}; out = []
    for i in (1, 2, 3, 5, 6, 8, 12): out.append((i, J[i - 1][0], J[i - 1][1], J[i - 1][2]))
    a, b = keep_cut(W)
    out.append((4, "keep gate cuts against the second-largest: cut = a x largest + b x second, b >= 0.5, |a| <= 0.2",
                f"a {a:.2f}, b {b:.2f}", bool(b >= 0.5 and abs(a) <= 0.2)))
    refs = hiding_refs(W); arc = hiding_refs(N(example()))
    ok = passed[7] and all(abs(refs[k][i] - arc[k][i]) <= 0.35 for k in (1, 2) for i in range(4))
    out.append((7, "hiding references are ARC's mixes: weight of the previous largest per neuron within 0.35 of ARC's (1 and 2 steps after a record), and job 7",
                " | ".join(f"{k} step: " + " ".join(f"{j}:{p:.2f}" for j, p in zip(HID, refs[k])) for k in (1, 2)), bool(ok)))
    X = lists(200_000, seed); good, allm = memory_modes(W, X)
    out.append((9, "memory rotates (basis-free): >= 2 turning pairs, modulus >= 0.7, memory participation >= 0.5",
                f"{len(good)} pairs (" + ", ".join(f"{d:.0f} deg |{m:.2f}| part {p:.2f}" for m, d, p in sorted(allm, key=lambda z: -z[0]) if m >= 0.5) + ")", len(good) >= 2))
    out.append((10, "switch-off ages 2, 5, 6 (score_twin job 10) on a rotating memory (job 9 here)",
                f"ages {'pass' if passed[10] else 'fail'}, rotation {'pass' if len(good) >= 2 else 'fail'}", bool(passed[10] and len(good) >= 2)))
    a0, a1, a2 = gap_use(W)
    out.append((11, "neuron 3 reads the gap from hiding and it is used: input replaced by the gap fit within 5 points, by another list's gap >= 10 points worse, and job 11",
                f"intact {100 * a0:.1f}%, gap fit {100 * a1:.1f}%, other list's gap {100 * a2:.1f}%, job 11 {'pass' if passed[11] else 'fail'}",
                bool(passed[11] and a0 - a1 <= 0.05 and a1 - a2 >= 0.10)))
    return sorted(out), sum(p for _, _, p in J)


if __name__ == "__main__":
    W = load(sys.argv[1]); res, scored = mechanism(W); n = 0
