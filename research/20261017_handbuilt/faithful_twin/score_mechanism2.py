"""Frozen mechanism scorer, version 2 (2026-10-21, after round 4): score_mechanism.py plus a hiding test on jobs 7 and 8.

Usage:  python -u score_mechanism2.py <weights.npz | module.py | ARC>   (16-neuron candidates in ARC's order)

Why: after round 4, networks passed jobs 7 and 8 with hiding slots that do not hide the largest (the hiding wave held
elsewhere), so those slots were trivially "rebuilt each step". The loophole was found after seeing round 4's results.
Added test (both jobs 7 and 8 also require it): silence the neurons of ARC's hiding slots (1, 6, 7, 8) for one step,
the step after the largest arrives (lists with the largest at steps 0-8; 400,000 lists, seed 31); the network must then
name the largest on at least HALF OF ARC'S RATE, measured here on the same lists (ARC: 81.3%, so the bar is about 41%;
the threshold is tied to ARC's own value, not a free number). Everything else as score_mechanism.py (frozen, unchanged).
Ranking from round 5: MECH2 count first, transplant mean second; score_mechanism.py's count reported alongside.
Last line: MECH2 jobs=<n>/12 passes=... (MECH jobs=<old n>/12). Do not edit this file (its hash is in LEDGER.md)."""
import sys
import numpy as np, torch
sys.path.insert(0, "/data/output/research/algzoo/20261017_handbuilt/faithful_twin")
from score_mechanism import mechanism, load, example, N  # noqa: E402
from score_wide import Net, lists, HID, DEV  # noqa: E402


def names_largest_when_silenced(net):
    X = lists(400_000, 31); L = X.argmax(1); keep = L <= 8; X, L = X[keep], L[keep]
    kill = torch.zeros(len(X), 10, dtype=torch.bool, device=DEV); kill[torch.arange(len(X), device=DEV), L + 1] = True
    Hw, _ = net.run(X, kill=(net.S(HID), kill)); return ((Hw[:, -1] @ net.Wt[2].T).argmax(1) == L).double().mean().item()


def hiding_test(net):
    arc = names_largest_when_silenced(Net(example(), np.eye(16))); c = names_largest_when_silenced(net)
    return c, arc, c >= 0.5 * arc


if __name__ == "__main__":
    W = load(sys.argv[1]); res, scored = mechanism(W); c, arc, ok = hiding_test(Net(W, np.eye(16)))
    print(f"== candidate {sys.argv[1]}: jobs by ARC's mechanism, version 2")
    print(f"  hiding test: silencing the hiding slots one step after the largest -> names the largest {100 * c:.1f}% (ARC {100 * arc:.1f}%, bar {50 * arc:.1f}%): {'pass' if ok else 'fail'}")
    n2 = n1 = 0; passes = []
    for i, name, val, p in res:
        p2 = p and (ok if i in (7, 8) else True); n1 += p; n2 += p2
        if p2: passes.append(i)
        print(f"  {'PASS' if p2 else 'FAIL'}  {i:2d} {name}{' + hiding test' if i in (7, 8) else ''}\n          {val}")
    print(f"MECH2 jobs={n2}/12 passes={','.join(map(str, passes))} (MECH jobs={n1}/12; score_twin jobs {scored}/12)")
