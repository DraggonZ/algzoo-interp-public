"""Frozen scorer for the wider track (2026-10-21): a hand-built network with up to 24 neurons, scored through a declared
fixed map onto ARC's 16 neuron slots.

Usage:  python -u score_wide.py <module.py | weights.npz | ARC> [--quick]
  module.py defines weights() -> (wi [n], wh [n, n] (wh[j, i] from i to j), wo [10, n]) and MAP, a [16, n] array: ARC
  neuron i corresponds to the activity MAP[i] @ h of the wider network. Each wider neuron may appear in at most one
  row of MAP (neurons in no row are helpers that belong to no ARC slot). Without MAP (or for npz files, ARC) the map is
  the identity and n must be 16. The map is part of the design: written down, never fitted to scores.

Everything below is score_mechanism.py's 12 tests and score_twin.py's transplants and nudges, rewritten for a mapped
network ("slot i" = MAP[i] @ h; "slot i's neurons" = the wider neurons with a nonzero entry in row i):
- on/off of a slot: its mapped activity > 0; pre-activation of a slot: MAP[i] @ (pre-activations);
- a slot's input weight: MAP[i] @ wi; removing or nudging a slot acts on its neurons;
- blindness: rows of every wider neuron outside the gates' neurons, read over the hiding slots' neurons;
- memory rotation: modes of the full wider matrix in the commonest on/off pattern, participation summed over the
  memory slots' neurons;
- neuron 3's input from the hiding neurons: for each of slot 3's neurons, its input from the hiding slots' neurons;
- transplants: ARC's slot i receives MAP[i] @ h of the wider network at every step; nudges scale a group's neurons;
- own accuracy: the wider network's own readout, 20 million lists.
Calibration (LEDGER.md): ARC with the identity map, ARC with one neuron split in two (exact copy), and the 16-neuron
candidates must give score_mechanism.py's counts.

Last line: WIDE mech=<n>/12 transplant_mean=<%> accuracy=<%> working=<yes|no> neurons=<n>.
Ranking within the wider track: mechanism count first, transplant mean second; under about 90% own accuracy does not
count as working. Do not edit this file (its hash is in LEDGER.md)."""
