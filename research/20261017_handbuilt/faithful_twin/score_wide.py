from score_twin import lists, so_far, corr, T, N, example, GROUPS, NUDGE_GROUPS, STORE, DET, KEEP, LATE, HID, MEM, GATES, SWITCH_AGES, DEV, DT  # noqa: E402

XS = torch.linspace(-1.0, 4.0, 5001, device=DEV, dtype=DT)


class Net:
    def __init__(self, W, M):
        self.W = N(W); self.M = np.asarray(M, float); self.n = len(self.W[0]); self.Wt = T(self.W)
        self.Mt = torch.tensor(self.M, device=DEV, dtype=DT)
        assert self.M.shape == (16, self.n) and self.n <= 24, "MAP must be [16, n], n <= 24"
        assert ((self.M != 0).sum(0) <= 1).all(), "each wider neuron may appear in at most one row of MAP"
        self.sup = {i: list(np.flatnonzero(self.M[i])) for i in range(16)}

    def S(self, slots): return sorted({k for i in slots for k in self.sup[i]})

    def run(self, X, kill=None, nudge=None):
        """Wider states and pre-activations [n_lists, 10, n]. kill = (wider neurons, step mask [n_lists, 10]) set to 0
        after those steps; nudge = (wider neurons, step, factor)."""
        h = torch.zeros(len(X), self.n, device=DEV, dtype=DT); H, P = [], []
        for t in range(10):
            p = h @ self.Wt[1].T + X[:, t:t + 1] * self.Wt[0]; h = torch.relu(p)
            if kill is not None:
                ks, m = kill; h = h.clone(); idx = torch.nonzero(m[:, t]).flatten()
                for k in ks: h[idx, k] = 0
            if nudge is not None and t == nudge[1]: h = h.clone(); h[:, nudge[0]] *= nudge[2]
            H.append(h); P.append(p)
        return torch.stack(H, 1), torch.stack(P, 1)

    def mapped(self, Hw): return Hw @ self.Mt.T

    def win(self, i): return float(self.M[i] @ self.W[0])


def load(arg):
    if arg == "ARC": return Net(example(), np.eye(16))
    if arg.endswith(".npz"):
        d = np.load(arg); return Net([d["wi"], d["wh"], d["wo"]], np.eye(16))
    spec = importlib.util.spec_from_file_location("cand", arg); m = importlib.util.module_from_spec(spec); spec.loader.exec_module(m)
    W = m.weights(); return Net(W, getattr(m, "MAP", np.eye(len(np.asarray(W[0])))))


def first_x(net, X, cond):
    Hw, _ = net.run(X); ok = cond(net.mapped(Hw)); i = torch.nonzero(ok).flatten()
    return XS[i[0]].item() if len(i) else np.nan


def keep_cut(net):
    rows = []
    for M in (1.5, 2.0, 2.5):
        for S in (0.3, 0.6, 0.9, 1.2):
            X = torch.full((len(XS), 10), -1.0, device=DEV, dtype=DT); X[:, 0] = M; X[:, 1] = S; X[:, 4] = XS
            rows.append((M, S, first_x(net, X, lambda H: H[:, 5, KEEP] > 0)))
    A = np.array([[M, S, 1] for M, S, _ in rows]); y = np.array([c for *_, c in rows]); ok = ~np.isnan(y)
    if ok.sum() < 4: return np.nan, np.nan
    co, *_ = np.linalg.lstsq(A[ok], y[ok], rcond=None); return co[0], co[1]


def hiding_refs(net):
    out = {}
    for k in (1, 2):
        rows = []
        for P in (0.5, 0.9, 1.3):
            for M in (1.6, 2.0, 2.4):
                X = torch.full((len(XS), 10), -1.0, device=DEV, dtype=DT); X[:, 1] = P; X[:, 2] = M; X[:, 2 + k] = XS
                rows.append((P, M, [first_x(net, X, lambda H, j=j: H[:, 2 + k, j] <= 0) for j in HID]))
        A = np.array([[P, M, 1] for P, M, _ in rows]); Y = np.array([o for *_, o in rows]); ps = []
        for i in range(4):
            ok = ~np.isnan(Y[:, i]); ps.append(np.linalg.lstsq(A[ok], Y[ok, i], rcond=None)[0][0] if ok.sum() >= 4 else np.nan)
        out[k] = ps
    return out


def gap_use(net, n=400_000, seed=21):
    X = lists(n, seed); Hw, _ = net.run(X); Xc = X.cpu().numpy(); hs = net.S(HID); s3 = net.sup[3]
    Wh = net.Wt[1]; D = {k: (Hw[:, :, hs] @ Wh[k, hs]).cpu().numpy() for k in s3}
    _, _, _, age = so_far(X); agn = age.cpu().numpy(); rng = np.random.default_rng(5)
    rep_a = {k: np.zeros((n, 10)) for k in s3}; rep_b = {k: np.zeros((n, 10)) for k in s3}
    for t in range(1, 10):
        v = -np.sort(-Xc[:, :t], 1); gap = v[:, 0] - (v[:, 1] if t >= 2 else 0.0); ag = agn[:, t - 1]
        for a in range(t):
            m = np.flatnonzero(ag == a); perm = rng.permutation(m)
            for k in s3:
                y = D[k][:, t - 1]
                if len(m) < 50: rep_a[k][m, t] = rep_b[k][m, t] = y[m]; continue
                A = np.c_[gap[m], np.ones(len(m))]; c, *_ = np.linalg.lstsq(A, y[m], rcond=None)
                rep_a[k][m, t] = A @ c; rep_b[k][m, t] = np.c_[gap[perm], np.ones(len(m))] @ c
    def acc(rep):
        Rr = None if rep is None else {k: torch.tensor(v, device=DEV, dtype=DT) for k, v in rep.items()}
        h = torch.zeros(n, net.n, device=DEV, dtype=DT)
        for t in range(10):
            p = h @ Wh.T + X[:, t:t + 1] * net.Wt[0]
            if Rr is not None and t >= 1:
                p = p.clone()
                for k in s3: p[:, k] = p[:, k] - h[:, hs] @ Wh[k, hs] + Rr[k][:, t]
            h = torch.relu(p)
        return ((h @ net.Wt[2].T).argmax(1) == X.argsort(1, descending=True)[:, 1]).double().mean().item()
    return acc(None), acc(rep_a), acc(rep_b)


def mechanism(net, seed=7, n=200_000):
    X = lists(n, seed); Hw, Pw = net.run(X); H = net.mapped(Hw); P = net.mapped(Pw); on = H > 0
    M, S, rec, age = so_far(X); out = []
    c = corr(H[:, 3:, STORE].reshape(-1), M[:, 3:].reshape(-1))
    out.append((1, "store (2) follows the largest so far: correlation >= 0.9", f"{c:.3f}", c >= 0.9))
    r, o = rec[:, 1:], on[:, 1:, DET]; a, b = o[r].double().mean().item(), o[~r].double().mean().item()
    out.append((2, "new-largest (4) on at records >= 0.9, elsewhere <= 0.05", f"{a:.3f} / {b:.3f}", a >= 0.9 and b <= 0.05))
    c = corr(H[:, 1:, DET][r], (X[:, 1:] - M[:, 1:])[r])
    out.append((3, "new-largest (4) size follows the amount beaten: correlation >= 0.75", f"{c:.3f}", c >= 0.75))
    ka, kb = keep_cut(net)
    out.append((4, "keep gate cuts against the second-largest: cut = a x largest + b x second, b >= 0.5, |a| <= 0.2",
                f"a {ka:.2f}, b {kb:.2f}", bool(kb >= 0.5 and abs(ka) <= 0.2)))
    a = on[:, 2:10, LATE][rec[:, 1:9]].double().mean().item(); b = on[:, 2:10, LATE][~rec[:, 1:9]].double().mean().item()
    out.append((5, "late gate (9) on one step after a record >= 0.9, elsewhere <= 0.05", f"{a:.3f} / {b:.3f}", a >= 0.9 and b <= 0.05))
    kill = torch.zeros_like(rec); kill[:, 2:9] = rec[:, 1:8]
    H2 = net.mapped(net.run(X, kill=(net.sup[LATE], kill))[0]); m = torch.zeros_like(rec); m[:, 3:10] = rec[:, 1:8]
    sd = H.reshape(-1, 16).std(0).clamp(min=1e-12); eff = {j: ((H2[:, :, j] - H[:, :, j]).abs()[m].mean() / sd[j]).item() for j in HID}
    ok = min(eff[1], eff[6]) >= 0.04 and min(eff[1], eff[6]) >= 3 * max(eff[7], eff[8])
    out.append((6, "late gate's push two steps after a record: on 1 and 6 >= 0.04 sd and >= 3x that on 7 and 8", " ".join(f"{j}:{eff[j]:.2f}" for j in HID), ok))
    # job 7: score_twin's test (mapped) and the references
    offr = [1 - o_[r].double().mean().item() for o_ in (on[:, 1:, j] for j in HID)]; onn = [on[:, 1:, j][~r].double().mean().item() for j in HID]
    Mx, Sx = M[:, 2:9].reshape(-1), S[:, 2:9].reshape(-1); A3 = torch.stack([Mx, Sx, torch.ones_like(Mx)], 1); r2s = []
    for j in HID:
        ref = (-(P[:, 2:9, j] - X[:, 2:9] * net.win(j)) / net.win(j)).reshape(-1)
        cf = torch.linalg.lstsq(A3, ref[:, None]).solution[:, 0]; r2s.append(1 - ((A3 @ cf - ref).var() / ref.var()).item())
    j7 = all(v >= 0.85 for v in offr) and all(v >= 0.65 for v in onn) and all(v >= 0.6 for v in r2s) and all(net.win(j) < 0 for j in HID)
    refs = hiding_refs(net); arc = hiding_refs(Net(example(), np.eye(16)))
    ok = j7 and all(abs(refs[k][i] - arc[k][i]) <= 0.35 for k in (1, 2) for i in range(4))
    out.append((7, "hiding references are ARC's mixes (previous largest weight per neuron within 0.35 of ARC's) and switched off by records",
                f"off {' '.join(f'{v:.2f}' for v in offr)}; on {' '.join(f'{v:.2f}' for v in onn)}; R2 {' '.join(f'{v:.2f}' for v in r2s)} | " +
                " | ".join(f"{k} step: " + " ".join(f"{j}:{p:.2f}" for j, p in zip(HID, refs[k])) for k in (1, 2)), bool(ok)))
    # job 8
    Xp = X[X.argmax(1) <= 3][:50000]; hs = net.S(HID); woc = net.Wt[2][:, hs] - net.Wt[2][:, hs].mean(0)
    a_, _ = net.run(Xp); b_, _ = net.run(Xp, nudge=(hs, 5, 0.9)); A6, B6 = net.mapped(a_[:, 6])[:, HID], net.mapped(b_[:, 6])[:, HID]
    left = ((B6 - A6).norm(dim=1) / A6.norm(dim=1).clamp(min=1e-9)).median().item() / 0.1
    leftr = (((b_[:, 6, hs] - a_[:, 6, hs]) @ woc.T).norm(dim=1) / (a_[:, 6, hs] @ woc.T).norm(dim=1).clamp(min=1e-12)).median().item() / 0.1
    out.append((8, "hiding rebuilt each step: share of a 10% nudge at step 5 left at step 6, activity <= 0.3 and readout view <= 0.8",
                f"activity {left:.3f}, readout view {leftr:.3f}", left <= 0.3 and leftr <= 0.8))
    # job 9, 10
    onw = Hw > 0; pats = Counter(map(lambda q: q.tobytes(), onw[:, 4:9].reshape(-1, net.n).cpu().numpy()))
    top = np.frombuffer(pats.most_common(1)[0][0], dtype=bool); ms = net.S(MEM)
    ev, L, Rv = sl.eig(np.diag(top.astype(float)) @ net.W[1], left=True, right=True); modes = []
    for k in range(len(ev)):
        if np.imag(ev[k]) <= 0: continue
        lr = np.conj(L[:, k]) * Rv[:, k]; modes.append((abs(ev[k]), np.degrees(abs(np.angle(ev[k]))), float(np.real(lr[ms].sum() / lr.sum()))))
    good = [m_ for m_ in modes if 3 < m_[1] < 177 and m_[0] >= 0.7 and m_[2] >= 0.5]
    out.append((9, "memory rotates (basis-free): >= 2 turning pairs, modulus >= 0.7, memory participation >= 0.5",
                f"{len(good)} pairs (" + ", ".join(f"{d:.0f} deg |{mm:.2f}| part {p:.2f}" for mm, d, p in sorted(modes, key=lambda z: -z[0]) if mm >= 0.5) + ")", len(good) >= 2))
    AG = age[:, 1:]; offm = ~on[:, 1:]; res = []
    for j, a0 in SWITCH_AGES.items():
        res.append((j, a0, offm[:, :, j][AG == a0].double().mean().item(), offm[:, :, j][AG != a0].double().mean().item()))
    j10 = all(at >= 0.85 and ot <= 0.30 for _, _, at, ot in res)
    out.append((10, "memory 0, 11, 10 switch off at ages 2, 5, 6 (off >= 0.85 there, <= 0.30 elsewhere) on a rotating memory (job 9)",
                "  ".join(f"{j}@{a0}: {at:.2f}/{ot:.2f}" for j, a0, at, ot in res) + f"; rotation {'pass' if len(good) >= 2 else 'fail'}", bool(j10 and len(good) >= 2)))
    # job 11
    Xc = X.cpu().numpy(); Pn = P[:, :, 3].cpu().numpy(); agn = age.cpu().numpy(); cells = []
    for t in range(3, 10):
        v = -np.sort(-Xc[:, :t + 1], 1)[:, :3]
        for a0 in (1, 2):
            mm = (agn[:, t] == a0) & (v[:, 0] > 0); A = np.c_[v[mm], np.ones(mm.sum())]; y = Pn[mm, t]
            cf, *_ = np.linalg.lstsq(A, y, rcond=None); gp = v[mm, 0] - v[mm, 1]
            cells.append((cf[0] > 0 and cf[1] < 0, np.corrcoef(gp, y)[0, 1] ** 2 if y.std() > 1e-12 else 0.0))
    j11 = np.mean([s for s, _ in cells]) >= 0.75 and np.median([q for _, q in cells]) >= 0.1
    a0_, a1_, a2_ = gap_use(net)
    out.append((11, "neuron 3 reads the gap from hiding and it is used: input replaced by the gap fit within 5 points, by another list's gap >= 10 points worse; gap in its activity",
                f"intact {100 * a0_:.1f}%, gap fit {100 * a1_:.1f}%, other list's gap {100 * a2_:.1f}%, gap in activity {'pass' if j11 else 'fail'}",
                bool(j11 and a0_ - a1_ <= 0.05 and a1_ - a2_ >= 0.10)))
    bl = []
    for i in [k for k in range(net.n) if k not in net.S(GATES)]:
        t_ = net.W[1][i, hs] * net.W[0][hs]; bl.append(abs(t_.sum()) / (np.abs(t_).sum() + 1e-30))
    out.append((12, "blindness: rows outside the gates read hiding at right angles (median ratio <= 0.1)", f"median {np.median(bl):.3f}", np.median(bl) <= 0.1))
    return out


def transplants(net):
    import full_mean
    Ta = T(example()); V, wt = full_mean.grid(40, 48); V = torch.tensor(V, device=DEV, dtype=DT); wt = torch.tensor(wt, device=DEV, dtype=DT)
    def grid_acc(cols, own=False):
        nV = len(wt); tot = torch.zeros((), device=DEV, dtype=DT)
        for i in range(0, 720, 16):
            tt = full_mean.T[i:i + 16]; pos = tt.repeat_interleave(nV, 0); val = V.repeat(len(tt), 1); n = len(pos)
            bmu = -torch.exp(-val[:, 2] ** 2 / 2) / np.sqrt(2 * np.pi) / (0.5 * (1 + torch.erf(val[:, 2] / np.sqrt(2))))
            X = bmu[:, None].repeat(1, 10); ar = torch.arange(n, device=DEV)
            for k in range(3): X[ar, pos[:, k]] = val[:, k]
            hT = torch.zeros(n, 16, device=DEV, dtype=DT); hW = torch.zeros(n, net.n, device=DEV, dtype=DT)
            for t in range(10):
                hW = torch.relu(hW @ net.Wt[1].T + X[:, t:t + 1] * net.Wt[0]); hT = torch.relu(hT @ Ta[1].T + X[:, t:t + 1] * Ta[0])
                if cols is not None: hT = hT.clone(); hT[:, cols] = (hW @ net.Mt.T)[:, cols]
            S = hW @ net.Wt[2].T if own else hT @ Ta[2].T
            tot += ((S.argmax(1) == pos[:, 1]).to(DT) * wt.repeat(len(tt))).sum()
        return (tot / (wt.sum() * 720)).item()
    res = {"ARC alone": grid_acc(None), "candidate alone (own readout)": grid_acc(None, own=True)}
    for g, idx in GROUPS.items(): res[g] = grid_acc(idx)
    return res


def nudges(net):
    import shifts
    a = shifts.shifts(T(example()), NUDGE_GROUPS); b = shifts.shifts(net.Wt, {g: net.S(v) for g, v in NUDGE_GROUPS.items()})
    keys = list(a); va = np.array([a[k] for k in keys]); vb = np.array([b[k] for k in keys])
    return keys, va, vb, int((np.sign(va) == np.sign(vb)).sum()), float(np.median(np.abs(vb) / np.abs(va)))


def accuracy(net, seed=1000, n=20_000_000, chunk=2_000_000):
    right = 0
    for c in range(n // chunk):
        X = lists(chunk, seed + c); h = torch.zeros(chunk, net.n, device=DEV, dtype=DT)
        for t in range(10): h = torch.relu(h @ net.Wt[1].T + X[:, t:t + 1] * net.Wt[0])
        right += ((h @ net.Wt[2].T).argmax(1) == X.argsort(1, descending=True)[:, 1]).sum().item()
    return right / n


