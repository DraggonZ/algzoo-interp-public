"""Frozen faithfulness scorer for hand-built 16-neuron networks laid out in ARC's neuron order (2026-10-21).

Usage:  python -u score_twin.py <weights.npz | module.py | ARC> [--seed S] [--quick]
  weights.npz: arrays wi [16], wh [16, 16] (wh[j, i] from i to j), wo [10, 16], in ARC's neuron order.
  module.py:   a file defining weights() -> (wi, wh, wo) in ARC's neuron order (numpy arrays).
  --seed S:    list seed offset (default 0). Jobs use seed 7 + S, accuracy 1000 + S, transplants are on a fixed grid
               (no lists), nudges use the battery's fixed lists. Used only to measure the scorer's noise.
  --quick:     jobs only (no transplants, nudges or accuracy).

ARC's groups (fixed): store 2, new-largest detector 4, keep gate 5, late gate 9, hiding 1, 6, 7, 8,
memory 0, 3, 10, 11, 12, 13, 14, 15. The candidate must put each job in ARC's slot.

Prints four parts:
1. Jobs checklist: one line per job, the same test on ARC and on the candidate, PASS or FAIL with the measured
   value. Pass bands were set from the job's wording and ARC's own value before any candidate was scored.
2. Transplants: ARC's accuracy with one group replaced at every step by the candidate's values (both networks run
   on the same inputs; hilton/faithful/faithful.py), on the sampling-free grid of the three largest numbers.
3. Nudge battery (superposition/twin/shifts.py): lead shifts under memory, store, keep and hiding nudges; same sign as
   ARC out of 12 and the median size ratio.
4. Own accuracy on 20 million lists; secondary: near-tie measures and the redraw test of the close-call mosaic.
Last line: SCORE jobs=<passed>/<total> transplant_mean=<%> accuracy=<%> working=<yes|no>.

Ranking (ledger): more jobs passed first; ties broken by the mean transplant accuracy; under about 90% own accuracy
does not count as working. Do not edit this file (its hash is in LEDGER.md)."""
import argparse, importlib.util, itertools, sys
import numpy as np, torch

R = "/data/output/research/algzoo/20261017_handbuilt"
sys.path[:0] = [R + "/family", R + "/superposition/twin", R + "/hilton/propagate"]
from algzoo.core import example  # noqa: E402

DEV, DT = "cuda", torch.float64
STORE, DET, KEEP, LATE = 2, 4, 5, 9
HID = [1, 6, 7, 8]
MEM = [0, 3, 10, 11, 12, 13, 14, 15]
GATES = [KEEP, LATE]
GROUPS = {"store and detector (2, 4)": [2, 4], "keep gate (5)": [5], "late gate (9)": [9],
          "hiding (1, 6, 7, 8)": HID, "memory (0, 3, 10-15)": MEM}
NUDGE_GROUPS = {"store": [2, 4], "keep": [5], "hiding": HID, "memory": MEM}
SWITCH_AGES = {0: 2, 11: 5, 10: 6}      # ARC's memory neurons that switch off at a fixed age of the largest


def T(W): return [torch.tensor(np.asarray(a, float), device=DEV, dtype=DT) for a in W]
def N(W): return [np.asarray(a, float) for a in W]


def load(arg):
    if arg == "ARC": return N(example())
    if arg.endswith(".npz"):
        d = np.load(arg); return N([d["wi"], d["wh"], d["wo"]])
    spec = importlib.util.spec_from_file_location("cand", arg); m = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(m); return N(m.weights())


def lists(n, seed): return torch.randn(n, 10, device=DEV, dtype=DT, generator=torch.Generator(device=DEV).manual_seed(seed))


def run(W, X, kill=None):
    """States [n, 10, 16] and pre-activations. kill = (neuron, step mask [n, 10]): that neuron's value is set to 0
    after the given steps (its output to the next step is removed)."""
    h = torch.zeros(len(X), 16, device=DEV, dtype=DT); H, P = [], []
    for t in range(10):
        p = h @ W[1].T + X[:, t:t + 1] * W[0]; h = torch.relu(p)
        if kill is not None:
            j, m = kill; h = h.clone(); h[m[:, t], j] = 0
        H.append(h); P.append(p)
    return torch.stack(H, 1), torch.stack(P, 1)


def so_far(X):
    """Before step t: largest, second-largest (n, 10; -inf where undefined); records: x_t positive and above every
    earlier number, t >= 1; age of the largest after step t."""
    n = len(X); M = torch.full((n, 10), -np.inf, device=DEV, dtype=DT); S = M.clone()
    for t in range(1, 10):
        v = X[:, :t].sort(1, descending=True).values; M[:, t] = v[:, 0]
        if t >= 2: S[:, t] = v[:, 1]
    rec = (X > M) & (X > 0); rec[:, 0] = False
    pos = torch.zeros(n, 10, dtype=torch.long, device=DEV); cur = torch.zeros(n, dtype=torch.long, device=DEV)
    for t in range(1, 10):
        cur = torch.where(X[:, t] > X[torch.arange(n, device=DEV), cur], torch.full_like(cur, t), cur); pos[:, t] = cur
    return M, S, rec, torch.arange(10, device=DEV)[None] - pos


def corr(a, b):
    a = a - a.mean(); b = b - b.mean(); return (a * b).mean().item() / (a.std().item() * b.std().item() + 1e-30)


def jobs(W, seed=7, n=200_000):
    """Returns list of (job, value string, passed)."""
    Wt = T(W); X = lists(n, seed); H, P = run(Wt, X); on = H > 0; M, S, rec, age = so_far(X); out = []
    # 1 store follows the largest so far (correlation with the largest before step t, steps 3-9; roles.py)
    c = corr(H[:, 3:, STORE].reshape(-1), M[:, 3:].reshape(-1))
    out.append(("store (2) follows the largest so far: correlation >= 0.9", f"{c:.3f}", c >= 0.9))
    # 2 detector fires only when the arriving number beats the largest so far
    r, o = rec[:, 1:], on[:, 1:, DET]; a, b = o[r].double().mean().item(), o[~r].double().mean().item()
    out.append(("new-largest (4) on at records >= 0.9, elsewhere <= 0.05", f"{a:.3f} / {b:.3f}", a >= 0.9 and b <= 0.05))
    # 3 ... by about the amount it beats it
    c = corr(H[:, 1:, DET][r], (X[:, 1:] - M[:, 1:])[r])
    out.append(("new-largest (4) size follows the amount beaten: correlation >= 0.75", f"{c:.3f}", c >= 0.75))
    # 4 keep gate: on one step after a number >= c x second-largest so far (non-records, steps 2-8); after records on
    nr = ~rec[:, 2:9] & (S[:, 2:9] > 0); ratio = (X[:, 2:9] / S[:, 2:9])[nr]; g = on[:, 3:10, KEEP][nr]
    cs = np.round(np.arange(0.30, 1.21, 0.01), 2)
    agree = np.array([((ratio >= cc) == g).double().mean().item() for cc in cs]); cbest = cs[agree.argmax()]
    after = on[:, 2:10, KEEP][rec[:, 1:9]].double().mean().item()
    ok = 0.6 <= cbest <= 0.85 and agree.max() >= 0.85 and after >= 0.9
    out.append(("keep gate (5): cut c in 0.6-0.85 x second-largest, agreement >= 0.85, on after records >= 0.9",
                f"c {cbest:.2f}, agreement {agree.max():.3f}, after records {after:.3f}", ok))
    # 5 late gate on one step after a record only
    a = on[:, 2:10, LATE][rec[:, 1:9]].double().mean().item(); b = on[:, 2:10, LATE][~rec[:, 1:9]].double().mean().item()
    out.append(("late gate (9) on one step after a record >= 0.9, elsewhere <= 0.05", f"{a:.3f} / {b:.3f}", a >= 0.9 and b <= 0.05))
    # 6 its push reaches hiding 1 and 6 two steps after: remove 9's value one step after each record (steps 2..8),
    #   change in 1 and 6 at the following step, in units of each neuron's activity sd; compare with 7 and 8
    kill = torch.zeros_like(rec); kill[:, 2:9] = rec[:, 1:8]
    H2, _ = run(Wt, X, kill=(LATE, kill)); m = torch.zeros_like(rec); m[:, 3:10] = rec[:, 1:8]
    sd = H.reshape(-1, 16).std(0).clamp(min=1e-12); eff = {j: ((H2[:, :, j] - H[:, :, j]).abs()[m].mean() / sd[j]).item() for j in HID}
    ok = min(eff[1], eff[6]) >= 0.04 and min(eff[1], eff[6]) >= 3 * max(eff[7], eff[8])
    out.append(("late gate's push two steps after a record: on 1 and 6 >= 0.04 sd and >= 3x that on 7 and 8",
                " ".join(f"{j}:{eff[j]:.2f}" for j in HID), ok))
    # 7 hiding neurons switch off when a number beats their reference (roles.py criteria, each of the four),
    #   and the reference is the largest so far mixed with the second (fit R2 >= 0.6), input weight negative
    r, o = rec[:, 1:], on[:, 1:]
    offr = [1 - o[:, :, j][r].double().mean().item() for j in HID]; onn = [o[:, :, j][~r].double().mean().item() for j in HID]
    Mx, Sx = M[:, 2:9].reshape(-1), S[:, 2:9].reshape(-1); A3 = torch.stack([Mx, Sx, torch.ones_like(Mx)], 1); r2s = []
    for j in HID:
        ref = (-(H[:, 1:8] @ Wt[1][j]) / W[0][j]).reshape(-1)
        cf = torch.linalg.lstsq(A3, ref[:, None]).solution[:, 0]; r2s.append(1 - ((A3 @ cf - ref).var() / ref.var()).item())
    ok = all(a >= 0.85 for a in offr) and all(b >= 0.65 for b in onn) and all(v >= 0.6 for v in r2s) and all(W[0][j] < 0 for j in HID)
    out.append(("hiding (1, 6, 7, 8) off at records >= 0.85, on elsewhere >= 0.65, reference = largest/second mix R2 >= 0.6",
                "off " + " ".join(f"{v:.2f}" for v in offr) + "; on " + " ".join(f"{v:.2f}" for v in onn) +
                "; R2 " + " ".join(f"{v:.2f}" for v in r2s), ok))
    # 8 hiding rebuilt each step: scale 1, 6, 7, 8 by 0.9 at step 5 (lists with the largest by step 3); share of the
    #   change left at step 6, (a) in the hiding neurons' activity (superposition/twin/hide_persist.py; ARC 0.2 of the
    #   nudge, a self-holding clock 1) and (b) in what the readout takes from them, centred over positions (a level
    #   shared by all positions does not count; ARC 0.73, a self-holding clock about 0.9). Pass: (a) <= 0.3 and (b) <= 0.8.
    Xp = X[X.argmax(1) <= 3][:50000]; woc = Wt[2][:, HID] - Wt[2][:, HID].mean(0)
    def st(nudge):
        h = torch.zeros(len(Xp), 16, device=DEV, dtype=DT); o = []
        for t in range(10):
            h = torch.relu(h @ Wt[1].T + Xp[:, t:t + 1] * Wt[0])
            if nudge and t == 5: h = h.clone(); h[:, HID] *= 0.9
            o.append(h)
        return o
    a, b = st(False), st(True); d6 = b[6][:, HID] - a[6][:, HID]
    left = (d6.norm(dim=1) / a[6][:, HID].norm(dim=1).clamp(min=1e-9)).median().item() / 0.1
    leftr = ((d6 @ woc.T).norm(dim=1) / (a[6][:, HID] @ woc.T).norm(dim=1).clamp(min=1e-12)).median().item() / 0.1
    out.append(("hiding rebuilt each step: share of a 10% nudge at step 5 left at step 6, activity <= 0.3 and readout view <= 0.8",
                f"activity {left:.3f}, readout view {leftr:.3f}", left <= 0.3 and leftr <= 0.8))
    # 9 memory as a rotating code: readout row k+1 = row k pushed one step through the dynamics in the commonest
    #   on/off pattern (median cosine k = 0..7 >= 0.9) and the memory block rotates (>= 2 turning pairs, modulus >= 0.7)
    from collections import Counter
    pats = Counter(map(lambda q: q.tobytes(), on[:, 4:9].reshape(-1, 16).cpu().numpy()))
    top = np.frombuffer(pats.most_common(1)[0][0], dtype=bool)
    sig = H.reshape(-1, 16).std(0).cpu().numpy(); sig = np.where(sig > 1e-12, sig, 1.0)
    wh = W[1] * sig[None, :] / sig[:, None]; wo = W[2] * sig[None, :]
    Mx_ = np.diag(top.astype(float)) @ wh; Wc = wo - wo.mean(0); Pp = Wc[:-1] @ Mx_; Pp = Pp - Pp.mean(0)
    cosk = [Pp[k] @ Wc[k + 1] / (np.linalg.norm(Pp[k]) * np.linalg.norm(Wc[k + 1]) + 1e-30) for k in range(9)]
    ev = np.linalg.eigvals(W[1][np.ix_(MEM, MEM)]); ang = np.degrees(np.abs(np.angle(ev))); mod = np.abs(ev)
    turning = int((((ang > 3) & (ang < 177)) & (mod >= 0.7)).sum() // 2); medc = float(np.median(cosk[:8]))
    out.append(("memory turns votes as a rotating code: push cosine >= 0.9 and >= 2 turning pairs (modulus >= 0.7)",
                f"cosine {medc:.3f}, turning pairs {turning} (angles " + " ".join(f"{a:.0f}" for a, mm in sorted(set(zip(np.round(ang), np.round(mod, 2)))) if 3 < a < 177 and mm >= 0.7) + ")",
                medc >= 0.9 and turning >= 2))
    # 10 memory neurons 0, 11, 10 switch off at ages 2, 5, 6 of the largest (off >= 0.85 at that age, <= 0.30 at others)
    AG = age[:, 1:]; offm = ~on[:, 1:]; res = []
    for j, a0 in SWITCH_AGES.items():
        at = offm[:, :, j][AG == a0].double().mean().item(); other = offm[:, :, j][AG != a0].double().mean().item()
        res.append((j, a0, at, other))
    ok = all(at >= 0.85 and other <= 0.30 for _, _, at, other in res)
    out.append(("memory 0, 11, 10 switch off at ages 2, 5, 6 of the largest (off >= 0.85 there, <= 0.30 elsewhere)",
                "  ".join(f"{j}@{a0}: {at:.2f}/{ot:.2f}" for j, a0, at, ot in res), ok))
    # 11 neuron 3 carries the gap between the largest and the second so far: in cells (step 3-9, largest 1-2 steps
    #   old), least squares of its pre-activation on (largest, second, third, const): largest positive, second negative
    #   in >= 75% of cells, and median R2 of the gap alone >= 0.1 (neuron3/gap.py)
    Xc = X.cpu().numpy(); Pn = P[:, :, 3].cpu().numpy(); agn = age.cpu().numpy(); cells = []
    for t in range(3, 10):
        v = -np.sort(-Xc[:, :t + 1], 1)[:, :3]
        for a0 in (1, 2):
            mm = (agn[:, t] == a0) & (v[:, 0] > 0)
            A = np.c_[v[mm], np.ones(mm.sum())]; y = Pn[mm, t]
            cf, *_ = np.linalg.lstsq(A, y, rcond=None); gp = v[mm, 0] - v[mm, 1]
            r2g = np.corrcoef(gp, y)[0, 1] ** 2 if y.std() > 1e-12 else 0.0
            cells.append((cf[0] > 0 and cf[1] < 0, r2g))
    signs = np.mean([s for s, _ in cells]); r2g = float(np.median([r for _, r in cells]))
    out.append(("neuron 3 carries the gap: signs right in >= 75% of cells, median R2 of gap alone >= 0.1",
                f"signs {signs:.2f}, R2 {r2g:.3f}", signs >= 0.75 and r2g >= 0.1))
    # 12 blindness: rows outside the gates read the hiding neurons at right angles to their input weights
    #   |sum_j W[i,j] w_j| / sum_j |W[i,j] w_j| over hiding j; median over rows <= 0.1 (random signs about 0.46)
    bl = []
    for i in [i for i in range(16) if i not in GATES]:
        t_ = W[1][i, HID] * W[0][HID]; bl.append(abs(t_.sum()) / (np.abs(t_).sum() + 1e-30))
    tr = W[2][:, HID] * W[0][HID]; blo = np.abs(tr.sum(1)) / (np.abs(tr).sum(1) + 1e-30)
    out.append(("blindness: recurrent rows outside the gates read hiding at right angles (median ratio <= 0.1)",
                f"median {np.median(bl):.3f} (readout rows {np.median(blo):.3f})", np.median(bl) <= 0.1))
    return out


# ---- transplants (hilton/faithful/faithful.py, grid 40 x 48) ----
def transplants(Wc):
    import full_mean
    Ta, Tc = T(example()), T(Wc)
    V, wt = full_mean.grid(40, 48); V = torch.tensor(V, device=DEV, dtype=DT); wt = torch.tensor(wt, device=DEV, dtype=DT)

    def grid_acc(step, wo):
        nV = len(wt); tot = torch.zeros((), device=DEV, dtype=DT)
        for i in range(0, 720, 16):
            tt = full_mean.T[i:i + 16]; pos = tt.repeat_interleave(nV, 0); val = V.repeat(len(tt), 1); n = len(pos)
            bmu = -torch.exp(-val[:, 2] ** 2 / 2) / np.sqrt(2 * np.pi) / (0.5 * (1 + torch.erf(val[:, 2] / np.sqrt(2))))
            X = bmu[:, None].repeat(1, 10); ar = torch.arange(n, device=DEV)
            for k in range(3): X[ar, pos[:, k]] = val[:, k]
            hT = torch.zeros(n, 16, device=DEV, dtype=DT); hH = torch.zeros(n, 16, device=DEV, dtype=DT)
            for t in range(10): hT, hH = step(hT, hH, X[:, t:t + 1])
            tot += (((hT @ wo.T).argmax(1) == pos[:, 1]).to(DT) * wt.repeat(len(tt))).sum()
        return (tot / (wt.sum() * 720)).item()

    def patch(cols):
        def step(hT, hH, x):
            hH2 = torch.relu(hH @ Tc[1].T + x * Tc[0]); hT2 = torch.relu(hT @ Ta[1].T + x * Ta[0])
            hT2[:, cols] = hH2[:, cols]; return hT2, hH2
        return step
    res = {"ARC alone": grid_acc(lambda a, b, x: (torch.relu(a @ Ta[1].T + x * Ta[0]), b), Ta[2]),
           "candidate alone (own readout)": grid_acc(lambda a, b, x: (torch.relu(a @ Tc[1].T + x * Tc[0]), b), Tc[2])}
    for g, idx in GROUPS.items(): res[g] = grid_acc(patch(torch.tensor(idx, device=DEV)), Ta[2])
    return res


# ---- nudges (superposition/twin/shifts.py) ----
def nudges(Wc):
    import shifts
    a = shifts.shifts(T(example()), NUDGE_GROUPS); b = shifts.shifts(T(Wc), NUDGE_GROUPS)
    keys = list(a); va = np.array([a[k] for k in keys]); vb = np.array([b[k] for k in keys])
    return keys, va, vb, int((np.sign(va) == np.sign(vb)).sum()), float(np.median(np.abs(vb) / np.abs(va)))


# ---- own accuracy and close calls ----
def accuracy(Wc, seed, n=20_000_000, chunk=2_000_000):
    Wt = T(Wc); right = tot = 0; nt = ntr = nt3 = 0
    for c in range(n // chunk):
        X = lists(chunk, seed + c); h = torch.zeros(chunk, 16, device=DEV, dtype=DT)
        for t in range(10): h = torch.relu(h @ Wt[1].T + X[:, t:t + 1] * Wt[0])
        pred = (h @ Wt[2].T).argmax(1); o = X.argsort(1, descending=True); ok = pred == o[:, 1]
        right += ok.sum().item(); tot += chunk
        v = X.gather(1, o); near = ((v[:, 1] - v[:, 2]) < 0.05 * v[:, 1].abs()) & (v[:, 1] > 0)
        nt += near.sum().item(); ntr += (near & ok).sum().item(); nt3 += (near & (pred == o[:, 2])).sum().item()
    return right / tot, ntr / nt, nt3 / nt


def redraw(Wc):
    """paper/figures/fig_mosaic_dense.py: 400 near-tie lists (seed 11), 40 variants each with the seven smaller numbers
    redrawn below the third; share of lists whose answer depends on the background (no answer in >= 90% of variants)."""
    rng = np.random.default_rng(11); Nn, Rr = 400, 40; L = []
    while len(L) < Nn:
        x = rng.standard_normal(10); v = np.sort(x)[::-1]
        if v[1] > 0 and v[1] - v[2] < 0.05 * v[1]: L.append(x)
    X, rk = [], []
    for x in L:
        o = np.argsort(-x); third = x[o[2]]
        for _ in range(Rr):
            y = x.copy(); z = rng.standard_normal(7)
            while (bad := z >= third).any(): z[bad] = rng.standard_normal(bad.sum())
            y[o[3:]] = z; X.append(y); rk.append((o[1], o[2]))
    X = torch.tensor(np.array(X), device=DEV, dtype=DT); rk = np.array(rk); Wt = T(Wc)
    h = torch.zeros(len(X), 16, device=DEV, dtype=DT)
    for t in range(10): h = torch.relu(h @ Wt[1].T + X[:, t:t + 1] * Wt[0])
    a = (h @ Wt[2].T).argmax(1).cpu().numpy(); g = np.where(a == rk[:, 0], 0, np.where(a == rk[:, 1], 1, 2)).reshape(Nn, Rr)
    cnt = np.stack([(g == k).sum(1) for k in range(3)], 1)
    return (cnt.max(1) < 0.9 * Rr).mean(), (cnt[:, 0] == Rr).mean(), (cnt[:, 1] == Rr).mean()


