"""Frozen wider-track scorer, version 2 (2026-10-21, after round 4): score_wide.py plus the hiding test of
score_mechanism2.py on jobs 7 and 8 (silence the hiding slots' neurons, through the map, for one step after the largest
arrives; the network must name the largest on at least half of ARC's rate on the same lists, ARC 81.3%). The loophole
was found after seeing round 4's results; the threshold is tied to ARC's own value. score_wide.py is frozen, unchanged.
Usage:  python -u score_wide2.py <module.py | ARC> [--quick]
Last line: WIDE2 mech=<n>/12 (old <n>) transplant_mean=<%> accuracy=<%> working=<yes|no> neurons=<n>.
Ranking within the wider track from round 5: WIDE2 mech count first, transplant mean second. Do not edit this file."""
import argparse, sys
import numpy as np
sys.path.insert(0, "/data/output/research/algzoo/20261017_handbuilt/faithful_twin")
from score_wide import load, mechanism, transplants, accuracy, GROUPS  # noqa: E402
from score_mechanism2 import hiding_test  # noqa: E402

if __name__ == "__main__":
    ap = argparse.ArgumentParser(); ap.add_argument("weights"); ap.add_argument("--quick", action="store_true"); a = ap.parse_args()
    net = load(a.weights); res = mechanism(net); c, arc, ok = hiding_test(net)
    print(f"== candidate {a.weights}: {net.n} neurons; version 2")
    print(f"  hiding test: silencing the hiding slots one step after the largest -> names the largest {100 * c:.1f}% (ARC {100 * arc:.1f}%, bar {50 * arc:.1f}%): {'pass' if ok else 'fail'}")
    n1 = n2 = 0; passes = []
    for i, name, val, p in res:
        p2 = p and (ok if i in (7, 8) else True); n1 += p; n2 += p2
        if p2: passes.append(i)
        print(f"  {'PASS' if p2 else 'FAIL'}  {i:2d} {name}{' + hiding test' if i in (7, 8) else ''}\n          {val}")
    if a.quick:
        print(f"WIDE2 mech={n2}/12 (old {n1}) passes={','.join(map(str, passes))} transplant_mean=nan accuracy=nan working=nan neurons={net.n}"); sys.exit()
    tr = transplants(net); tmean = np.mean([tr[g] for g in GROUPS]); acc = accuracy(net)
    for k, v in tr.items(): print(f"  transplant {k:32s} {100 * v:6.2f}%")
    print(f"WIDE2 mech={n2}/12 (old {n1}) passes={','.join(map(str, passes))} transplant_mean={100 * tmean:.2f} accuracy={100 * acc:.2f} working={'yes' if acc >= 0.90 else 'no'} neurons={net.n}")
